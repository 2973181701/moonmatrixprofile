import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const result = spawnSync('moon', ['build', '--release', '--target', 'js', '--deny-warn'], { cwd: root, stdio: 'inherit' });
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);
mkdirSync(new URL('../web/', import.meta.url), { recursive: true });
copyFileSync(new URL('../_build/js/release/build/bridge/bridge.js', import.meta.url), new URL('../web/core.js', import.meta.url));
console.log('Built MoonBit core → web/core.js');
